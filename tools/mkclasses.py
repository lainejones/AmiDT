"""mkclasses.py - the per-format class files (src/dt/dt_<fmt>.c) and the datatype descriptors
(out/DataTypes/<Name>, for DEVS:DataTypes) for every AmiDT format.  Each class is the shared side
(dt_lib.c) plus one call into its core, so they are generated from this one table.

    python tools/mkclasses.py
"""
import os, sys, time
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import dtd

A = -1                                          # any byte
FORMATS = [
    # fmt,  descriptor name, what,              core header,  call,          quant, pattern,          mask
    ('png', 'PNG',   'fast 8-bit PNG',      'pngdec.h',  'png_decode(rd, h, dt_al, dt_fr, q, o)', 1, '#?',     [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a]),
    ('gif', 'GIF',   'fast GIF',            'gifdec.h',  'gif_decode(rd, h, dt_al, dt_fr, o)',    0, '#?',     [0x47, 0x49, 0x46, 0x38, A, 0x61]),
    ('bmp', 'BMP',   'fast 8-bit BMP',      'bmpdec.h',  'bmp_decode(rd, h, dt_al, dt_fr, q, o)', 1, '#?',     [0x42, 0x4d]),
    ('tga', 'TGA',   'fast 8-bit Targa',    'moredec.h', 'tga_decode(rd, h, dt_al, dt_fr, q, o)', 1, '#?.tga', []),
    ('pcx', 'PCX',   'fast PCX',            'moredec.h', 'pcx_decode(rd, h, dt_al, dt_fr, q, o)', 1, '#?.pcx', [0x0a, A, 0x01]),
    ('ico', 'ICO',   'Windows icons',       'moredec.h', 'ico_decode(rd, h, dt_al, dt_fr, q, o)', 1, '#?.ico', [0x00, 0x00, 0x01, 0x00]),
    ('qoi', 'QOI',   'QOI pictures',        'moredec.h', 'qoi_decode(rd, h, dt_al, dt_fr, q, o)', 1, '#?',     [0x71, 0x6f, 0x69, 0x66]),
]

QUANT = '''static struct quant *q;                    /* read-only after dt_init: shared by every caller */

int dt_init(void)
{
    if (!(q = AllocVec(sizeof(*q), MEMF_ANY))) return 0;
    q_init(q);
    return 1;
}

void dt_cleanup(void) { if (q) FreeVec(q), q = NULL; }
'''
NOQUANT = '''int dt_init(void) { return 1; }            /* palette only: no colour tables */
void dt_cleanup(void) { }
'''

def cls(fmt, name, what, inc, call, quant):
    return ('/* dt_%s.c - %s.datatype (AmiDT): the %s core (src/core) behind the shared datatype side.\n'
            ' * Generated by tools/mkclasses.py. */\n' % (fmt, fmt, name)
            + '#include <exec/memory.h>\n#include <dos/dos.h>\n#include <proto/exec.h>\n#include "dt_lib.h"\n'
            + '#include "../core/%s"\n\n' % inc
            + 'const char dt_libname[] = DT_LIBNAME;\n'
            + 'const char dt_idstring[] = "%s.datatype " DT_VERSTR " (" DT_DATE ") AmiDT - %s\\r\\n";\n' % (fmt, what)
            + 'static const char __attribute__((used)) verstag[] = "$VER: %s.datatype " DT_VERSTR " (" DT_DATE ") AmiDT";\n\n' % fmt
            + (QUANT if quant else NOQUANT) + '\n'
            + 'static int dec(dt_read_fn rd, void *h, struct png_out *o) { return %s; }\n\n' % call
            + 'int dt_load(Class *cl, Object *o) { (void)cl; return dt_decode_file(o, dec, "%s"); }\n' % name)

if __name__ == '__main__':
    os.makedirs(os.path.join(ROOT, 'out', 'DataTypes'), exist_ok=True)
    t = time.localtime()
    date = '%d.%d.%d' % (t.tm_mday, t.tm_mon, t.tm_year)
    for fmt, name, what, inc, call, quant, pattern, mask in FORMATS:
        open(os.path.join(ROOT, 'src', 'dt', 'dt_%s.c' % fmt), 'w', newline='\n').write(cls(fmt, name, what, inc, call, quant))
        d = dtd.make(name, fmt, pattern, mask, int.from_bytes(b'pict', 'big'), int.from_bytes(fmt.encode() + b' ', 'big'),
                     ver='$VER: %s 47.100 (%s) AmiDT' % (name, date))
        open(os.path.join(ROOT, 'out', 'DataTypes', name), 'wb').write(d)
    print('classes + descriptors:', ' '.join(f[1] for f in FORMATS))
